export function getChakraBySlug(slug) {
  if (!slug) return null;
  const normalized = slug.toLowerCase().trim().replace(/[^a-z0-9]/g, "");
  return (
    CHAKRAS_ARRAY.find((c) => {
      const cSlug = c.slug.toLowerCase().replace(/[^a-z0-9]/g, "");
      const cId = c.id.toLowerCase().replace(/[^a-z0-9]/g, "");
      const cSanskrit = c.sanskritName.toLowerCase().replace(/[^a-z0-9]/g, "");
      const cEnglish = c.englishName.toLowerCase().replace(/[^a-z0-9]/g, "");

      return (
        cSlug === normalized ||
        cId === normalized ||
        cSanskrit === normalized ||
        cEnglish === normalized ||
        cSlug.includes(normalized) ||
        normalized.includes(cId)
      );
    }) || null
  );
}

